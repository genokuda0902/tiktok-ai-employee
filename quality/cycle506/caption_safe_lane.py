#!/usr/bin/env python3
"""Fail-closed, 10-genre caption-safe review renderer. Reimplementation, not v33.

Source media must be rights-approved; never publish this output automatically.
No Japanese speech is generated by this module and captions are not speech-synced.
"""
import argparse
import json
import math
import subprocess
from pathlib import Path

GENRES = frozenset('ai_work gadgets study travel cooking beauty home fitness history business'.split())
WIDTH, HEIGHT, SECONDS = 1080, 1920, 20
VIDEO_W, VIDEO_H, VIDEO_X, VIDEO_Y = 864, 1536, 108, 24
CAPTION_BOX = (48, 1574, 984, 130)
SAFE_CAPTION_BOTTOM = 1710

def check(manifest):
    if manifest.get('genre') not in GENRES:
        raise ValueError('unknown genre')
    if manifest.get('rights') != 'original_procedural':
        raise ValueError('unapproved source rights')
    if (manifest.get('publication'), manifest.get('human_review'), manifest.get('auto_post')) != ('NOT_APPROVED', 'HUMAN_REVIEW', False):
        raise ValueError('publication must fail closed')
    if manifest.get('narration_status') != 'NOT_AVAILABLE':
        raise ValueError('speech alignment cannot be claimed')
    items = manifest.get('captions')
    if not isinstance(items, list) or len(items) != 8:
        raise ValueError('8 caption intervals required')
    prev = 0.0
    for item in items:
        if set(item) != {'start', 'end', 'text', 'tag'}:
            raise ValueError('invalid caption fields')
        s, e = item['start'], item['end']
        if type(s) not in (float, int) or type(e) not in (float, int) or not math.isfinite(s+e):
            raise ValueError('nonfinite time')
        if abs(s-prev) > 1e-6 or e <= s or e > SECONDS:
            raise ValueError('caption timing invalid')
        prev = e
        t = item['text']
        if not isinstance(t, str) or not 2 <= len(t) <= 20 or any(c in t for c in '{}\\\n\r'):
            raise ValueError('unsafe caption')
    if abs(prev-SECONDS) > 1e-6:
        raise ValueError('incomplete timeline')
    if VIDEO_Y+VIDEO_H > CAPTION_BOX[1] or CAPTION_BOX[1]+CAPTION_BOX[3] > SAFE_CAPTION_BOTTOM:
        raise ValueError('caption/source collision or unsafe bottom')
    return items

def timestamp(s):
    return f'{int(s//3600)}:{int(s%3600//60):02}:{s%60:05.2f}'

def make_ass(manifest, path):
    clips = check(manifest)
    head = """[Script Info]
Title: 10-genre caption safe lane review only
ScriptType: v4.00+
PlayResX: 1080
PlayResY: 1920
WrapStyle: 2
ScaledBorderAndShadow: yes
[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,Noto Sans CJK JP,57,&H00FFFFFF,&H0000FFFF,&H000C1420,&H000C1420,-1,0,0,0,100,100,0,0,1,2,0,2,60,60,249,1
[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    rows = [f"Dialogue: 0,{timestamp(c['start'])},{timestamp(c['end'])},Default,,0,0,0,,{{\\fad(100,90)}}{c['text']}" for c in clips]
    path.write_text(head+'\n'.join(rows)+'\n', encoding='utf-8')

def probe(path):
    p = subprocess.run(['ffprobe','-v','error','-show_entries','stream=codec_type,codec_name,width,height:format=duration','-of','json',str(path)],check=True,capture_output=True,text=True)
    return json.loads(p.stdout)

def render(src, out, manifest, ass):
    check(manifest)
    p = probe(src)
    video = next((x for x in p['streams'] if x['codec_type']=='video'), {})
    if (video.get('width'), video.get('height')) != (WIDTH, HEIGHT) or abs(float(p['format']['duration'])-SECONDS) > .08:
        raise ValueError('source must be 1080x1920 and 20s')
    if not any(x['codec_type']=='audio' for x in p['streams']):
        raise ValueError('source must have audio')
    if src.resolve() == out.resolve():
        raise ValueError('do not overwrite source')
    make_ass(manifest, ass)
    vf=(f'scale={VIDEO_W}:{VIDEO_H}:flags=lanczos,'
        f'pad={WIDTH}:{HEIGHT}:{VIDEO_X}:{VIDEO_Y}:color=0x07182b,'
        f'drawbox=x=48:y=1574:w=984:h=130:color=0x12334a:t=fill,'
        f'drawbox=x=48:y=1574:w=9:h=130:color=0x32e2d1:t=fill,'
        f'ass={ass.as_posix()}')
    cmd=['ffmpeg','-nostdin','-hide_banner','-loglevel','error','-y','-i',str(src),'-vf',vf,'-map','0:v:0','-map','0:a:0','-c:v','libx264','-preset','veryfast','-crf','20','-pix_fmt','yuv420p','-r','30','-c:a','copy','-t','20','-movflags','+faststart','-metadata','comment=HUMAN_REVIEW; PUBLICATION_NOT_APPROVED',str(out)]
    subprocess.run(cmd,check=True)
    return cmd

if __name__ == '__main__':
    p=argparse.ArgumentParser()
    for n in ('input','output','manifest','ass'):p.add_argument('--'+n,required=True,type=Path)
    a=p.parse_args()
    m=json.loads(a.manifest.read_text(encoding='utf-8'))
    render(a.input,a.output,m,a.ass)
    print(json.dumps({'output':str(a.output),'status':'HUMAN_REVIEW','narration':'NOT_AVAILABLE'},ensure_ascii=False))
